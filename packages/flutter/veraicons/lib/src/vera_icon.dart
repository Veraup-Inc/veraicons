  @override
  Widget build(BuildContext context) {
    final dir = switch (tone) {
      VeraIconTone.duotone => 'duotone-rounded',
      VeraIconTone.duotoneStandard => 'duotone-standard',
      VeraIconTone.twotone => 'twotone-rounded',
      VeraIconTone.bulk => 'bulk-rounded',
    };
    final c = color ?? IconTheme.of(context).color ?? const Color(0xFF000000);
    return SvgPicture.asset(
      'assets/$dir/$name.svg',
      package: 'veraicons',
      width: size,
      height: size,
      colorFilter: ColorFilter.mode(c, BlendMode.srcIn),
    );
  }
